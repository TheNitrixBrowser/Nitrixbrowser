'use strict'
const {app,BrowserWindow,webContents,clipboard,ClipboardItem}=require('electron')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),http=require('node:http'),assert=require('node:assert/strict')
const profile=fs.mkdtempSync(path.join(os.tmpdir(),'nitrix-context-'))
app.setPath('appData',profile);process.env.XDG_DATA_HOME=path.join(profile,'data');process.env.XDG_CONFIG_HOME=path.join(profile,'config')
app.commandLine.appendSwitch('ozone-platform','headless')
let oldClipboard=null
async function restoreClipboard(){if(oldClipboard!==null){if(oldClipboard.length)await clipboard.write(oldClipboard);else clipboard.clear()}}
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms))
async function until(fn,label){for(let i=0;i<150;i++){try{if(await fn())return}catch{}await pause(80)}throw Error('Timeout: '+label)}
const watchdog=setTimeout(async()=>{await restoreClipboard();app.exit(1)},45000)
const server=http.createServer((_req,res)=>{res.setHeader('Content-Type','text/html');res.end('<p id="text">Nitrix clipboard test</p><input id="field">')})
server.listen(0,'127.0.0.1',async()=>{
 const base='http://127.0.0.1:'+server.address().port
 fs.mkdirSync(path.join(profile,'Nitrix'));fs.writeFileSync(path.join(profile,'Nitrix','settings.json'),JSON.stringify({startupBehavior:'custom',startupCustomUrl:base,lang:'pl'}))
 require('../main')
 try{
  await until(()=>BrowserWindow.getAllWindows().length,'window')
  oldClipboard=await Promise.all((await clipboard.read()).filter(item=>item.types.length).map(async item=>new ClipboardItem(Object.fromEntries(await Promise.all(item.types.map(async type=>[type,await item.getType(type)]))))))
  const win=BrowserWindow.getAllWindows()[0],run=code=>win.webContents.executeJavaScript(code)
  await until(()=>run('!!document.querySelector("webview") && !document.querySelector("webview").isLoading()'),'page')
  const guest=webContents.fromId(await run('document.querySelector("webview").getWebContentsId()'))
  const point=await guest.executeJavaScript(`{const p=document.getElementById('text'),r=document.createRange();r.selectNodeContents(p);getSelection().removeAllRanges();getSelection().addRange(r);const b=p.getBoundingClientRect();({x:Math.round(b.x+20),y:Math.round(b.y+8)})}`)
  guest.sendInputEvent({type:'mouseDown',button:'right',clickCount:1,...point});guest.sendInputEvent({type:'mouseUp',button:'right',clickCount:1,...point})
  await until(()=>run('!!document.querySelector("#ctx-menu.open [data-action=copy]")'),'copy menu')
  await run('document.querySelector("[data-action=copy]").click()')
  await until(async()=>await clipboard.readText()==='Nitrix clipboard test','copied text')
  const field=await guest.executeJavaScript(`{const e=document.getElementById('field');e.focus();const b=e.getBoundingClientRect();({x:Math.round(b.x+20),y:Math.round(b.y+8)})}`)
  guest.sendInputEvent({type:'mouseDown',button:'right',clickCount:1,...field});guest.sendInputEvent({type:'mouseUp',button:'right',clickCount:1,...field})
  await until(()=>run('!!document.querySelector("#ctx-menu.open [data-action=paste]")'),'paste menu')
  await run('document.querySelector("[data-action=paste]").click()')
  await until(()=>guest.executeJavaScript('document.getElementById("field").value==="Nitrix clipboard test"'),'pasted text')
  console.log('PASS actual right-click selection copy and input paste')
  await run('electronAPI.features.saveOptions({warnClose:false,sleepTabs:false,sleepMinutes:30,sleepExceptions:[]})')
  await run(`document.querySelector('.tab.active').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:60,clientY:20}));document.querySelector('[data-action="sleep-tab"]').click()`)
  await until(()=>run('!!document.querySelector(".nf-sleeping")'),'manual sleep')
  assert.equal(await run('!!document.querySelector("dialog[open]")'),false)
  assert.equal(guest.isDestroyed(),true)
  assert.equal(await run(`getComputedStyle(document.querySelector('.nf-sleeping .nf-moon')).display`),'block')
  await run('document.querySelector(".nf-sleeping").click()')
  await until(()=>run('!document.querySelector(".nf-sleeping") && !document.querySelector("webview.wv-active").isLoading()'),'wake')
  assert.equal(await run('document.querySelector("webview.wv-active").getURL()'),base+'/')
  console.log('PASS manual sleep while automatic sleep disabled, guest destroyed, moon shown, wake restores URL')
  await restoreClipboard();clearTimeout(watchdog);server.close();app.exit(0)
 }catch(error){console.error(error);await restoreClipboard();clearTimeout(watchdog);server.close();app.exit(1)}
})
